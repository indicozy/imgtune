import { afterAll, describe, expect, it } from "vitest";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import ts from "typescript";
import { backupFiles, instrument, restore } from "../src/instrument.js";
import { scanFile } from "../src/scan.js";

const CHILD = resolve(import.meta.dirname, "fixtures/restore-child.mjs");
const created: string[] = [];

function makeProject(files: Record<string, string>): string {
  const dir = mkdtempSync(join(tmpdir(), "imgtune-instrument-"));
  created.push(dir);
  for (const [rel, content] of Object.entries(files)) {
    const abs = join(dir, rel);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
  }
  return dir;
}

afterAll(async () => {
  for (const dir of created) await rm(dir, { recursive: true, force: true });
});

// `<Image` starts at line 3, column 12.
const CARD = [
  `import Image from "next/image";`,
  `export const Card = ({ p }: { p: { url: string } }) => (`,
  `${" ".repeat(11)}<Image src={p.url} sizes="33vw" width={300} height={200} alt="" />`,
  `);`,
  ``,
].join("\n");

const HERO = [
  `import Image from "next/image";`,
  `import hero from "./hero.png";`,
  `export const Hero = () => <Image src={hero} width={1} height={1} alt="" />;`,
  ``,
].join("\n");

const UNWRAP = `((s) => typeof s === "object" && s ? s.src : s)`;

describe("instrument and restore", () => {
  it("round trip: instruments the source, then restores it byte-for-byte", async () => {
    const dir = makeProject({ "src/Card.tsx": CARD });
    const file = join(dir, "src/Card.tsx");
    const original = readFileSync(file);
    const usages = scanFile(file, dir);

    await instrument(dir, usages);

    const edited = readFileSync(file, "utf8");
    expect(edited).toContain(`data-imgtune="src/Card.tsx:3:12"`);
    expect(edited).toContain(`data-imgtune-src={${UNWRAP}(p.url)}`);
    const { diagnostics } = ts.transpileModule(edited, {
      fileName: "Card.tsx",
      reportDiagnostics: true,
      compilerOptions: { jsx: ts.JsxEmit.Preserve },
    });
    expect(diagnostics ?? []).toHaveLength(0);

    const result = await restore(dir);
    expect(result.restored).toEqual([file]);
    expect(readFileSync(file).equals(original)).toBe(true);
    expect(existsSync(join(dir, ".imgtune/backup/manifest.json"))).toBe(false);
    expect(existsSync(join(dir, ".imgtune/backup/last-restored.json"))).toBe(true);
  });

  it("crash recovery: a new start restores a run that was never restored", async () => {
    const dir = makeProject({ "src/Card.tsx": CARD });
    const file = join(dir, "src/Card.tsx");
    const original = readFileSync(file);

    await instrument(dir, scanFile(file, dir));
    expect(readFileSync(file).equals(original)).toBe(false);

    // The killed run never called restore; the next start does.
    await restore(dir);
    expect(readFileSync(file).equals(original)).toBe(true);
    expect(existsSync(join(dir, ".imgtune/backup/manifest.json"))).toBe(false);
  });

  it("user edits preserved: restore returns the uncommitted content exactly", async () => {
    const edited = CARD.replace(`alt=""`, `alt="Hero shot"`) + `export const wip = 1; // my edit\n`;
    const dir = makeProject({ "src/Card.tsx": edited });
    const file = join(dir, "src/Card.tsx");

    await instrument(dir, scanFile(file, dir));
    await restore(dir);

    expect(readFileSync(file, "utf8")).toBe(edited);
  });

  it("double instrument refused while a manifest exists", async () => {
    const dir = makeProject({ "src/Card.tsx": CARD });
    const file = join(dir, "src/Card.tsx");
    const usages = scanFile(file, dir);

    await instrument(dir, usages);
    await expect(instrument(dir, usages)).rejects.toThrow("previous run not restored");
    await restore(dir);
  });

  it("side files: restores next-env.d.ts and tsconfig.json after they are rewritten", async () => {
    const nextEnv = `/// <reference types="next" />\n`;
    const tsconfig = `{"compilerOptions":{"strict":true}}\n`;
    const dir = makeProject({
      "src/Card.tsx": CARD,
      "next-env.d.ts": nextEnv,
      "tsconfig.json": tsconfig,
    });
    const file = join(dir, "src/Card.tsx");

    await instrument(dir, scanFile(file, dir));
    // `next dev` rewrites these two files.
    writeFileSync(join(dir, "next-env.d.ts"), `// generated by next dev\n`);
    writeFileSync(join(dir, "tsconfig.json"), `{}\n`);

    await restore(dir);
    expect(readFileSync(join(dir, "next-env.d.ts"), "utf8")).toBe(nextEnv);
    expect(readFileSync(join(dir, "tsconfig.json"), "utf8")).toBe(tsconfig);
  });

  it("static import src: unwraps .src for the recorded attribute", async () => {
    const dir = makeProject({ "src/Hero.tsx": HERO });
    const file = join(dir, "src/Hero.tsx");
    const original = readFileSync(file);

    await instrument(dir, scanFile(file, dir));
    expect(readFileSync(file, "utf8")).toContain(`data-imgtune-src={${UNWRAP}(hero)}`);

    await restore(dir);
    expect(readFileSync(file).equals(original)).toBe(true);
  });

  it("literal src: records the value, escaping quotes and ampersands", async () => {
    const src = [
      `import Image from "next/image";`,
      `export const A = () => (`,
      `  <>`,
      `    <Image src="/plain.png" width={1} height={1} alt="" />`,
      `    <Image src={'/a"b&c.png'} width={1} height={1} alt="" />`,
      `  </>`,
      `);`,
      ``,
    ].join("\n");
    const dir = makeProject({ "src/Lit.tsx": src });
    const file = join(dir, "src/Lit.tsx");

    await instrument(dir, scanFile(file, dir));
    const edited = readFileSync(file, "utf8");
    expect(edited).toContain(` data-imgtune-src="/plain.png"`);
    expect(edited).toContain(` data-imgtune-src="/a&quot;b&amp;c.png"`);

    await restore(dir);
  });

  it("backupFiles keeps the first copy when a file is backed up twice", async () => {
    const original = `export default {};\n`;
    const dir = makeProject({ "next.config.mjs": original });
    const file = join(dir, "next.config.mjs");

    await backupFiles(dir, [file]);
    writeFileSync(file, `export default { changed: true };\n`);
    await backupFiles(dir, [file]);

    await restore(dir);
    expect(readFileSync(file, "utf8")).toBe(original);
  });

  it("restore is a no-op without a manifest", async () => {
    const dir = makeProject({ "src/Card.tsx": CARD });
    expect(await restore(dir)).toEqual({ restored: [] });
  });
});

describe("installRestoreHandlers (child processes)", () => {
  function runChild(mode: string, dir: string) {
    return spawnSync(process.execPath, [CHILD, mode, dir, join(dir, "src/Card.tsx")], {
      encoding: "utf8",
      timeout: 20_000,
    });
  }

  it("SIGINT restores the files and exits 130", () => {
    const dir = makeProject({ "src/Card.tsx": CARD });
    const file = join(dir, "src/Card.tsx");
    const original = readFileSync(file);

    const child = runChild("sigint", dir);

    expect(child.status).toBe(130);
    expect(readFileSync(file).equals(original)).toBe(true);
    expect(existsSync(join(dir, ".imgtune/backup/manifest.json"))).toBe(false);
  });

  it("uncaught exception restores the files, prints the error and exits 1", () => {
    const dir = makeProject({ "src/Card.tsx": CARD });
    const file = join(dir, "src/Card.tsx");
    const original = readFileSync(file);

    const child = runChild("uncaught", dir);

    expect(child.status).toBe(1);
    expect(child.stderr).toContain("boom");
    expect(readFileSync(file).equals(original)).toBe(true);
  });

  it("a normal exit restores the files through the exit handler", () => {
    const dir = makeProject({ "src/Card.tsx": CARD });
    const file = join(dir, "src/Card.tsx");
    const original = readFileSync(file);

    const child = runChild("exit", dir);

    expect(child.status).toBe(0);
    expect(readFileSync(file).equals(original)).toBe(true);
  });

  it("installing twice registers a single SIGINT listener", () => {
    const dir = makeProject({ "src/Card.tsx": CARD });

    const child = runChild("count", dir);

    expect(child.status).toBe(0);
    expect(child.stdout.trim()).toBe("1");
  });
});
